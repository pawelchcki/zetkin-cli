#!/usr/bin/env python3
"""Normalize the pinned Zetkin v1 catalog and generate typed operation methods."""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "specs" / "v1_endpoints.json"
OUTPUT_PATH = ROOT / "src" / "zetkin_cli" / "generated" / "v1_operations.py"
SOURCE_COMMIT = "d013cb993187fb4e5a116b3275053602fd01ae9f"
SOURCE_URL = (
    "https://raw.githubusercontent.com/zetkin/developer.zetkin.org/"
    f"{SOURCE_COMMIT}/_data/resources.yml"
)


def parse_catalog(text: str) -> list[dict[str, Any]]:
    resources: list[dict[str, Any]] = []
    current: dict[str, Any] | None = None
    for line in text.splitlines():
        if line.startswith("- doc:"):
            if current and current.get("url"):
                resources.append(current)
            current = {"methods": []}
        elif current is not None and line.startswith("  docsection:"):
            current["section"] = line.split(":", 1)[1].strip()
        elif current is not None and line.startswith("    method:"):
            current["methods"].append(line.split(":", 1)[1].strip().upper())
        elif current is not None and line.startswith("  name:"):
            current["resource"] = line.split(":", 1)[1].strip()
        elif current is not None and line.startswith("  url:"):
            current["url"] = line.split(":", 1)[1].strip()
    if current and current.get("url"):
        resources.append(current)

    unique: dict[tuple[str, str], dict[str, Any]] = {}
    for resource in resources:
        for method in resource["methods"]:
            key = (method, resource["url"])
            unique.setdefault(
                key,
                {
                    "method": method,
                    "operation_id": operation_id(method, resource["url"]),
                    "path": resource["url"],
                    "resource": resource.get("resource", "UnknownResource"),
                    "section": resource.get("section", "unknown"),
                },
            )
    operations = sorted(unique.values(), key=lambda item: item["operation_id"])
    ids = [item["operation_id"] for item in operations]
    if len(ids) != len(set(ids)):
        duplicates = sorted({item for item in ids if ids.count(item) > 1})
        raise ValueError(f"Generated duplicate operation IDs: {duplicates}")
    if len(operations) != 256:
        raise ValueError(f"Expected 256 operations, found {len(operations)}")
    return operations


def operation_id(method: str, path: str) -> str:
    segments: list[str] = [method.lower()]
    for raw in path.strip("/").split("/"):
        if raw.startswith("{") and raw.endswith("}"):
            segments.extend(("by", sanitize(raw[1:-1])))
        else:
            segments.append(sanitize(raw))
    return "_".join(filter(None, segments))


def sanitize(value: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9]+", "_", value).strip("_").lower()
    if cleaned in {"from", "global", "import", "in", "is"}:
        return f"{cleaned}_"
    return cleaned


def path_parameters(path: str) -> list[str]:
    return [sanitize(value) for value in re.findall(r"\{([^}]+)\}", path)]


def render_path(path: str) -> str:
    rendered = path
    for original in re.findall(r"\{([^}]+)\}", path):
        rendered = rendered.replace(
            "{" + original + "}", "{" + sanitize(original) + "}"
        )
    return rendered


def render_method(operation: dict[str, Any], *, asynchronous: bool) -> str:
    params = path_parameters(operation["path"])
    signature = [f"{name}: int | str" for name in params]
    signature.extend(
        [
            "params: Params | None = None",
            "json: JsonValue = None",
        ]
    )
    prefix = "async def" if asynchronous else "def"
    await_prefix = "await " if asynchronous else ""
    joined = ",\n        ".join(signature)
    path = render_path(operation["path"])
    path_literal = f'f"{path}"' if params else f'"{path}"'
    return f'''    {prefix} {operation["operation_id"]}(
        self,
        *,
        {joined},
    ) -> ApiResult[JsonValue | bytes]:
        """{operation["method"]} {operation["path"]}."""
        return {await_prefix}self._client.request(
            "{operation["method"]}",
            {path_literal},
            version=1,
            params=params,
            json=json,
        )
'''


def render_module(operations: list[dict[str, Any]]) -> str:
    header = '''# Generated by scripts/generate_v1.py. Do not edit directly.
from __future__ import annotations

from typing import Protocol

from zetkin_cli.models import ApiResult, JsonValue
from zetkin_cli.transport import Params


class _SyncClient(Protocol):
    def request(
        self,
        method: str,
        path: str,
        *,
        version: int,
        params: Params | None = None,
        json: JsonValue = None,
    ) -> ApiResult[JsonValue | bytes]: ...


class _AsyncClient(Protocol):
    async def request(
        self,
        method: str,
        path: str,
        *,
        version: int,
        params: Params | None = None,
        json: JsonValue = None,
    ) -> ApiResult[JsonValue | bytes]: ...


class V1Operations:
    """All distinct method/path operations in the public v1 API catalog."""

    def __init__(self, client: _SyncClient) -> None:
        self._client = client

'''
    sync_methods = "\n".join(
        render_method(operation, asynchronous=False) for operation in operations
    )
    async_header = '''

class AsyncV1Operations:
    """Asynchronous form of every operation in :class:`V1Operations`."""

    def __init__(self, client: _AsyncClient) -> None:
        self._client = client

'''
    async_methods = "\n".join(
        render_method(operation, asynchronous=True) for operation in operations
    )
    return header + sync_methods + async_header + async_methods


def load_spec() -> list[dict[str, Any]]:
    payload = json.loads(SPEC_PATH.read_text())
    operations = payload.get("operations")
    if not isinstance(operations, list):
        raise ValueError("Invalid v1 endpoint specification")
    return operations


def write_spec(source: str) -> list[dict[str, Any]]:
    operations = parse_catalog(source)
    payload = {
        "source": SOURCE_URL,
        "source_commit": SOURCE_COMMIT,
        "operations": operations,
    }
    SPEC_PATH.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    return operations


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--source-file", type=Path)
    args = parser.parse_args()

    if args.refresh or args.source_file:
        if args.source_file:
            source = args.source_file.read_text()
        else:
            with urllib.request.urlopen(SOURCE_URL, timeout=30) as response:
                source = response.read().decode()
        operations = write_spec(source)
    else:
        operations = load_spec()
    rendered = render_module(operations)
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text() != rendered:
            print("Generated v1 operations are out of date", file=sys.stderr)
            return 1
        return 0
    OUTPUT_PATH.write_text(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
